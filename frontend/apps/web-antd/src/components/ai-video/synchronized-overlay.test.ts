import type { AiVideoCameraApi } from '#/api/ai-video/camera';

import { describe, expect, it } from 'vitest';

import { readSourceStamp } from './frame-stamp';
import { alignedOverlay } from './synchronized-overlay';

const streamId = '00000001-0000-0003-0000-000000000002';
const object: AiVideoCameraApi.OverlayObject = { class: 'person', trackId: 'track-1', confidence: 0.9,
  bbox: { x: 0.1, y: 0.2, width: 0.2, height: 0.5 },
  attributes: { helmet: 'absent', ppeBoxX: 0.12, ppeBoxY: 0.22, ppeBoxWidth: 0.05, ppeBoxHeight: 0.06 } };
function frame(pts: number): AiVideoCameraApi.OverlayFrame {
  return { cameraId: 2, sessionId: 's', taskId: 2, runId: 'current', streamId, sourcePts: pts,
    frameId: `frame-${pts}`, sourceWidth: 640, sourceHeight: 480, timestamp: Date.now(), objects: [object] };
}

describe('video and result timeline', () => {
  it('reads the runtime SEI, including escaped start codes and a 64-bit PTS', () => {
    // Generated by runtime stamp_h264; not a second implementation of its encoder.
    const hex = '00000001060528b60519ab079c4e199428f40aef3c91ec00000300010000030003000003000003000003000200000301000003015f90800000000165616263';
    const bytes = Uint8Array.from(hex.match(/../g)!, value => Number.parseInt(value, 16));
    expect(readSourceStamp(bytes.buffer)).toEqual({ streamId, sourcePts: 1_099_511_717_776 });
    expect(readSourceStamp(bytes.slice(0, 24).buffer)).toBeUndefined();
    const corrupted = bytes.slice(); corrupted[10] = 0;
    expect(readSourceStamp(corrupted.buffer)).toBeUndefined();
  });
  it('interpolates only the same tracked object and leaves evidence objects unchanged', () => {
    const a = frame(90_000); const b = frame(108_000);
    b.objects = [{ ...object, bbox: { ...object.bbox, x: 0.3 }, attributes: { ...object.attributes, ppeBoxX: 0.32 } }];
    const result = alignedOverlay([a, b], { streamId, sourcePts: 99_000 });
    expect(result?.frame.objects[0]?.bbox.x).toBeCloseTo(0.2);
    expect(result?.frame.objects[0]?.attributes.ppeBoxX).toBeCloseTo(0.22);
    expect(result?.anchorDistanceMs).toBe(100);
    expect(object.attributes.ppeBoxX).toBe(0.12);
    expect(result?.interpolated).toBe(true);
    b.objects[0]!.trackId = 'another-person';
    expect(alignedOverlay([a, b], { streamId, sourcePts: 99_000 })?.frame.objects[0]?.bbox.x).toBe(0.1);
  });
  it('drops delayed results and rejects frames from a disconnected stream', () => {
    expect(alignedOverlay([frame(90_000)], { streamId, sourcePts: 108_000 })).toBeUndefined();
    expect(alignedOverlay([frame(90_000)], { streamId: 'previous-stream', sourcePts: 90_000 })).toBeUndefined();
    const a = frame(90_000); const b = { ...frame(108_000), runId: 'another-run' };
    expect(alignedOverlay([a, b], { streamId, sourcePts: 99_000 })?.interpolated).toBe(false);
  });

  it('fills the middle of a bounded real track without treating it as a new detection', () => {
    const a = frame(90_000); const b = frame(118_800); // 320 ms between observations.
    b.objects = [{ ...object, bbox: { ...object.bbox, x: 0.3 },
      attributes: { ...object.attributes, ppeBoxX: 0.32 } }];
    const result = alignedOverlay([a, b], { streamId, sourcePts: 104_400 });
    expect(result?.interpolated).toBe(true);
    expect(result?.trackingSpanMs).toBe(320);
    expect(result?.anchorDistanceMs).toBe(160); // Honest distance to the actual model input.
    expect(result?.frame.sourcePts).toBe(104_400);
    expect(result?.frame.frameId).toBe(a.frameId); // Still the originating observation.
    expect(result?.frame.objects[0]?.attributes.ppeBoxX).toBeCloseTo(0.22);
    expect(a.objects[0]?.attributes.ppeBoxX).toBe(0.12);
    b.objects[0]!.attributes.helmet = 'present';
    expect(alignedOverlay([a, b], { streamId, sourcePts: 104_400 })).toBeUndefined();
  });

  it('never bridges lost identities, long gaps or missing head observations', () => {
    const a = frame(90_000); const b = frame(118_800);
    b.objects = [{ ...object, trackId: 'new-person' }];
    expect(alignedOverlay([a, b], { streamId, sourcePts: 104_400 })).toBeUndefined();
    b.objects = [{ ...object, attributes: { helmet: 'absent' } }];
    expect(alignedOverlay([a, b], { streamId, sourcePts: 104_400 })).toBeUndefined();
    expect(alignedOverlay([a, frame(144_000)], { streamId, sourcePts: 117_000 })).toBeUndefined();
  });
});

it('does not interpolate across a change in reflective vest status',()=>{
  const a=frame(90_000),b=frame(118_800);
  a.objects=[{...object,attributes:{vest:'absent'}}];
  b.objects=[{...object,attributes:{vest:'present'}}];
  expect(alignedOverlay([a,b],{streamId,sourcePts:104_400})).toBeUndefined();
});

it('interpolates the measured 480 ms NPU cadence but never extrapolates beyond observations',()=>{
  const a=frame(90_000),b=frame(133_200);
  b.objects=[{...object,bbox:{...object.bbox,x:.2},attributes:{...object.attributes,ppeBoxX:.22}}];
  const result=alignedOverlay([a,b],{streamId,sourcePts:111_600});
  expect(result?.interpolated).toBe(true);expect(result?.trackingSpanMs).toBe(480);
  expect(result?.frame.objects[0]?.bbox.x).toBeCloseTo(.15);
  expect(alignedOverlay([a,b],{streamId,sourcePts:151_200})).toBeUndefined();
});
