import type { AiVideoCameraApi } from '#/api/ai-video/camera';

import { describe, expect, it } from 'vitest';

import { readSourceStamp } from './frame-stamp';
import { alignedOverlay } from './synchronized-overlay';

const streamId = '00000001-0000-0003-0000-000000000002';
const object: AiVideoCameraApi.OverlayObject = {
  class: 'person',
  trackId: 'track-1',
  confidence: 0.9,
  bbox: { x: 0.1, y: 0.2, width: 0.2, height: 0.5 },
  attributes: {
    helmet: 'absent',
    ppeConfirmedPerson: true,
    ppeBoxX: 0.12,
    ppeBoxY: 0.22,
    ppeBoxWidth: 0.05,
    ppeBoxHeight: 0.06,
  },
};
function frame(pts: number): AiVideoCameraApi.OverlayFrame {
  return {
    cameraId: 2,
    sessionId: 's',
    taskId: 2,
    runId: 'current',
    streamId,
    sourcePts: pts,
    frameId: `frame-${pts}`,
    sourceWidth: 640,
    sourceHeight: 480,
    timestamp: Date.now(),
    objects: [object],
  };
}

describe('video and result timeline', () => {
  it('does not restore a rejected plate through the generic stationary hold', () => {
    const a = frame(90_000);
    a.objects = [
      {
        ...object,
        class: 'license_plate',
        attributes: {
          displayGeometryContinuity: true,
          visibleByDefault: true,
          displayLabel: '吉WD0011',
          displayState: 'normal',
        },
      },
    ];
    const b = { ...a, frameId: 'rejected', sourcePts: 99_000 };
    b.objects = [
      {
        ...a.objects[0]!,
        attributes: {
          displayGeometryContinuity: true,
          visibleByDefault: false,
          displayLabel: '车牌待确认',
          displayState: 'unknown',
          ocrStatus: 'UNSUPPORTED_FORMAT',
        },
      },
    ];
    const result = alignedOverlay([a, b], { streamId, sourcePts: 99_000 });
    expect(result?.heldObjects).toBe(0);
    expect(result?.frame.objects[0]?.attributes.visibleByDefault).toBe(false);
    expect(result?.frame.objects[0]?.attributes.displayLabel).toBe('车牌待确认');
  });

  it('keeps an opted-in candidate box continuous without announcing future OCR text', () => {
    const a = frame(90_000);
    const b = frame(181_800); // 1.02 seconds, including sampling jitter.
    a.objects = [
      {
        ...object,
        class: 'license_plate',
        attributes: {
          displayGeometryContinuity: true,
          visibleByDefault: true,
          displayLabel: '车牌待确认',
          displayState: 'unknown',
        },
      },
    ];
    b.objects = [
      {
        ...a.objects[0]!,
        bbox: { ...object.bbox, x: 0.3 },
        attributes: {
          ...a.objects[0]!.attributes,
          displayLabel: '吉WD0011',
          displayState: 'normal',
        },
      },
    ];
    for (let ms = 100; ms <= 1000; ms += 100) {
      const result = alignedOverlay([a, b], {
        streamId,
        sourcePts: 90_000 + ms * 90,
      });
      expect(result?.frame.objects).toHaveLength(1);
      expect(result?.frame.objects[0]?.attributes.displayLabel).toBe(
        '车牌待确认',
      );
      expect(result?.frame.objects[0]?.attributes.displayState).toBe('unknown');
    }
    expect(a.objects[0]!.bbox.x).toBe(0.1);
    b.objects[0]!.trackId = 'other';
    expect(
      alignedOverlay([a, b], { streamId, sourcePts: 153_000 }),
    ).toBeUndefined();
  });

  it('reads the runtime SEI, including escaped start codes and a 64-bit PTS', () => {
    // Generated by runtime stamp_h264; not a second implementation of its encoder.
    const hex =
      '00000001060528b60519ab079c4e199428f40aef3c91ec00000300010000030003000003000003000003000200000301000003015f90800000000165616263';
    const bytes = Uint8Array.from(hex.match(/../g)!, (value) =>
      Number.parseInt(value, 16),
    );
    expect(readSourceStamp(bytes.buffer)).toEqual({
      streamId,
      sourcePts: 1_099_511_717_776,
    });
    expect(readSourceStamp(bytes.slice(0, 24).buffer)).toBeUndefined();
    const corrupted = [...bytes];
    corrupted[10] = 0;
    expect(readSourceStamp(Uint8Array.from(corrupted).buffer)).toBeUndefined();
  });
  it('interpolates only the same tracked object and leaves evidence objects unchanged', () => {
    const a = frame(90_000);
    const b = frame(108_000);
    b.objects = [
      {
        ...object,
        bbox: { ...object.bbox, x: 0.3 },
        attributes: { ...object.attributes, ppeBoxX: 0.32 },
      },
    ];
    const result = alignedOverlay([a, b], { streamId, sourcePts: 99_000 });
    expect(result?.frame.objects[0]?.bbox.x).toBeCloseTo(0.2);
    expect(result?.frame.objects[0]?.attributes.ppeBoxX).toBeCloseTo(0.22);
    expect(result?.anchorDistanceMs).toBe(100);
    expect(object.attributes.ppeBoxX).toBe(0.12);
    expect(result?.interpolated).toBe(true);
    b.objects[0]!.trackId = 'another-person';
    expect(
      alignedOverlay([a, b], { streamId, sourcePts: 99_000 })?.frame.objects[0]
        ?.bbox.x,
    ).toBe(0.1);
  });
  it('expires retained results and rejects frames from a disconnected stream', () => {
    expect(
      alignedOverlay([frame(90_000)], { streamId, sourcePts: 153_000 }),
    ).toBeUndefined();
    expect(
      alignedOverlay([frame(90_000)], {
        streamId: 'previous-stream',
        sourcePts: 90_000,
      }),
    ).toBeUndefined();
    const a = frame(90_000);
    const b = { ...frame(108_000), runId: 'another-run' };
    expect(
      alignedOverlay([a, b], { streamId, sourcePts: 99_000 })?.interpolated,
    ).toBe(false);
  });

  it('fills the middle of a bounded real track without treating it as a new detection', () => {
    const a = frame(90_000);
    const b = frame(118_800); // 320 ms between observations.
    b.objects = [
      {
        ...object,
        bbox: { ...object.bbox, x: 0.3 },
        attributes: { ...object.attributes, ppeBoxX: 0.32 },
      },
    ];
    const result = alignedOverlay([a, b], { streamId, sourcePts: 104_400 });
    expect(result?.interpolated).toBe(true);
    expect(result?.trackingSpanMs).toBe(320);
    expect(result?.anchorDistanceMs).toBe(160); // Honest distance to the actual model input.
    expect(result?.frame.sourcePts).toBe(104_400);
    expect(result?.frame.frameId).toBe(a.frameId); // Still the originating observation.
    expect(result?.frame.objects[0]?.attributes.ppeBoxX).toBeCloseTo(0.22);
    expect(a.objects[0]?.attributes.ppeBoxX).toBe(0.12);
    b.objects[0]!.attributes.helmet = 'present';
    const changed = alignedOverlay([a, b], { streamId, sourcePts: 104_400 });
    expect(changed?.interpolated).toBe(false);
    expect(changed?.frame.objects).toEqual([]); // No stale position between different conclusions.
    expect(
      alignedOverlay([a, b], { streamId, sourcePts: b.sourcePts! })?.frame
        .objects[0]?.attributes.helmet,
    ).toBe('present');
  });

  it('never interpolates lost identities, long gaps or missing head observations', () => {
    const a = frame(90_000);
    const b = frame(118_800);
    b.objects = [{ ...object, trackId: 'new-person' }];
    expect(
      alignedOverlay([a, b], { streamId, sourcePts: 104_400 })?.interpolated,
    ).toBe(false);
    b.objects = [{ ...object, attributes: { helmet: 'absent' } }];
    expect(
      alignedOverlay([a, b], { streamId, sourcePts: 104_400 })?.interpolated,
    ).toBe(false);
    expect(
      alignedOverlay([a, frame(216_000)], { streamId, sourcePts: 162_000 }),
    ).toBeUndefined();
  });
});

it('does not interpolate across a change in reflective vest status', () => {
  const a = frame(90_000);
  const b = frame(118_800);
  a.objects = [{ ...object, attributes: { vest: 'absent' } }];
  b.objects = [{ ...object, attributes: { vest: 'present' } }];
  expect(
    alignedOverlay([a, b], { streamId, sourcePts: 104_400 })?.interpolated,
  ).toBe(false);
});

it('interpolates the measured 480 ms NPU cadence and bounds the final observation hold', () => {
  const a = frame(90_000);
  const b = frame(133_200);
  b.objects = [
    {
      ...object,
      bbox: { ...object.bbox, x: 0.2 },
      attributes: { ...object.attributes, ppeBoxX: 0.22 },
    },
  ];
  const result = alignedOverlay([a, b], { streamId, sourcePts: 111_600 });
  expect(result?.interpolated).toBe(true);
  expect(result?.trackingSpanMs).toBe(480);
  expect(result?.frame.objects[0]?.bbox.x).toBeCloseTo(0.15);
  const held = alignedOverlay([a, b], { streamId, sourcePts: 151_200 });
  expect(held?.frame.objects).toEqual([]); // A moving target must not leave a 200 ms trailing box.
  expect(held?.maxHoldAgeMs).toBe(0);
  expect(
    alignedOverlay([a, b], { streamId, sourcePts: 196_200 }),
  ).toBeUndefined();
});

it('interpolates a supplier display box independently and never bridges changed conclusions', () => {
  const a = frame(90_000);
  const b = frame(118_800);
  const attributes = {
    displayLabel: '外部目标',
    displayState: 'alert',
    displayConfidence: 0.74,
    displayBoxX: 0.12,
    displayBoxY: 0.22,
    displayBoxWidth: 0.05,
    displayBoxHeight: 0.06,
  };
  a.objects = [{ ...object, class: 'vendor-object', attributes }];
  b.objects = [
    {
      ...object,
      class: 'vendor-object',
      bbox: { ...object.bbox, x: 0.3 },
      attributes: { ...attributes, displayBoxX: 0.32, displayConfidence: 0.84 },
    },
  ];
  const stamp = { streamId, sourcePts: 104_400 };
  const result = alignedOverlay([a, b], stamp);
  expect(result?.interpolated).toBe(true);
  expect(result?.frame.objects[0]?.bbox.x).toBeCloseTo(0.2);
  expect(result?.frame.objects[0]?.attributes.displayBoxX).toBeCloseTo(0.22);
  expect(result?.frame.objects[0]?.attributes.displayConfidence).toBe(0.74);
  expect(a.objects[0]?.attributes.displayBoxX).toBe(0.12);
  for (const change of [
    { displayState: 'normal' },
    { displayLabel: '另一身份' },
    { displayBoxWidth: 0 },
    { displayBoxX: Number.NaN },
  ]) {
    b.objects[0]!.attributes = { ...attributes, displayBoxX: 0.32, ...change };
    expect(alignedOverlay([a, b], stamp)?.interpolated).toBe(false);
  }
  b.objects[0]!.attributes = {
    displayLabel: '外部目标',
    displayState: 'alert',
  };
  expect(alignedOverlay([a, b], stamp)?.interpolated).toBe(false);
});

describe('continuous annotations at a low inference frame rate', () => {
  it('fills all video frames between 520 ms detections without changing model scores', () => {
    const a = frame(90_000);
    const b = frame(136_800);
    b.objects = [
      {
        ...object,
        confidence: 0.5,
        bbox: { ...object.bbox, x: 0.3 },
        attributes: { ...object.attributes, ppeBoxX: 0.32 },
      },
    ];
    for (let milliseconds = 0; milliseconds <= 520; milliseconds += 40) {
      const result = alignedOverlay([a, b], {
        streamId,
        sourcePts: 90_000 + milliseconds * 90,
      });
      expect(result?.frame.objects).toHaveLength(1);
      expect(result?.frame.objects[0]?.confidence).toBe(
        milliseconds < 520 ? 0.9 : 0.5,
      );
    }
    expect(a.objects[0]?.bbox.x).toBe(0.1);
  });

  it('retains a measured stationary target for 600 ms without refreshing its age from a repaint', () => {
    const previous = frame(72_000);
    const a = frame(90_000);
    for (const milliseconds of [200, 400, 600]) {
      const result = alignedOverlay([previous, a], {
        streamId,
        sourcePts: 90_000 + milliseconds * 90,
      });
      expect(result?.heldObjects).toBe(1);
      expect(result?.maxHoldAgeMs).toBe(milliseconds);
      expect(result?.frame.sourcePts).toBe(a.sourcePts);
      expect(result?.frame.objects[0]?.bbox).toEqual(object.bbox);
    }
    expect(
      alignedOverlay([previous, a], { streamId, sourcePts: 144_090 }),
    ).toBeUndefined();
    expect(a.objects[0]?.attributes.overlayHeld).toBeUndefined();
  });

  it('bridges a missed detection while keeping the original expiry deadline', () => {
    const a = frame(90_000);
    const missing = { ...frame(117_000), objects: [] };
    const result = alignedOverlay([frame(72_000), a, missing], {
      streamId,
      sourcePts: 126_000,
    });
    expect(result?.frame.objects).toHaveLength(1);
    expect(result?.maxHoldAgeMs).toBe(400);
    const later = { ...frame(144_000), objects: [] };
    expect(
      alignedOverlay([a, missing, later], { streamId, sourcePts: 144_090 })
        ?.frame.objects,
    ).toEqual([]);
  });

  it('bridges an unknown observation but immediately accepts an explicit changed conclusion', () => {
    const a = frame(90_000);
    const unknown = {
      ...frame(117_000),
      objects: [
        {
          ...object,
          attributes: { displayState: 'unknown', visibleByDefault: false },
        },
      ],
    };
    const result = alignedOverlay([frame(72_000), a, unknown], {
      streamId,
      sourcePts: 126_000,
    });
    expect(result?.frame.objects[0]?.attributes.helmet).toBe('absent');
    expect(result?.maxHoldAgeMs).toBe(400);
    const normal = {
      ...frame(126_000),
      objects: [{ ...object, attributes: { helmet: 'present' } }],
    };
    expect(
      alignedOverlay([a, unknown, normal], { streamId, sourcePts: 126_000 })
        ?.frame.objects[0]?.attributes.helmet,
    ).toBe('present');
    expect(
      alignedOverlay([a, unknown, normal], { streamId, sourcePts: 126_000 })
        ?.heldObjects,
    ).toBe(0);
  });

  it.each(['runId', 'taskId', 'cameraId', 'streamId'] as const)(
    'does not retain observations across a changed %s',
    (key) => {
      const a = frame(90_000);
      const b = { ...frame(117_000), objects: [] };
      Object.assign(b, {
        [key]: key === 'taskId' || key === 'cameraId' ? 999 : 'replacement',
      });
      const result = alignedOverlay([a, b], {
        streamId: b.streamId!,
        sourcePts: 126_000,
      });
      expect(result?.frame.objects).toEqual([]);
    },
  );

  it('does not retain an old identity on top of a replacement track', () => {
    const a = frame(90_000);
    const b = {
      ...frame(117_000),
      objects: [{ ...object, trackId: 'replacement' }],
    };
    const result = alignedOverlay([a, b], { streamId, sourcePts: 117_000 });
    expect(result?.frame.objects.map((value) => value.trackId)).toEqual([
      'replacement',
    ]);
  });

  it('does not introduce objects or labels from a later frame early', () => {
    const a = { ...frame(90_000), objects: [] };
    const b = frame(135_000);
    expect(
      alignedOverlay([a, b], { streamId, sourcePts: 126_000 })?.frame.objects,
    ).toEqual([]);
  });
});

it('never animates between two heads associated with the same body track', () => {
  const a = frame(90_000);
  const b = frame(126_000);
  const display = {
    displayState: 'alert',
    displayLabel: '未佩戴安全帽',
    visibleByDefault: true,
    displayBoxX: 0.12,
    displayBoxY: 0.22,
    displayBoxWidth: 0.05,
    displayBoxHeight: 0.06,
  };
  a.objects = [{ ...object, attributes: display }];
  b.objects = [{ ...object, attributes: { ...display, displayBoxX: 0.24 } }];
  const middle = alignedOverlay([a, b], { streamId, sourcePts: 108_000 });
  expect(middle?.interpolated).toBe(false);
  expect(middle?.frame.objects).toEqual([]);
  expect(
    alignedOverlay([a, b], { streamId, sourcePts: 126_000 })?.frame.objects[0]
      ?.attributes.displayBoxX,
  ).toBe(0.24);
});

it('does not freeze an old head position after its body has moved or changed identity', () => {
  const previous = frame(72_000);
  const a = frame(90_000);
  const unknown = {
    ...frame(117_000),
    objects: [
      {
        ...object,
        bbox: { ...object.bbox, x: 0.2 },
        attributes: { displayState: 'unknown', visibleByDefault: false },
      },
    ],
  };
  const result = alignedOverlay([previous, a, unknown], {
    streamId,
    sourcePts: 117_000,
  });
  expect(result?.heldObjects).toBe(0);
  expect(result?.frame.objects[0]?.attributes.displayState).toBe('unknown');
  expect(result?.frame.objects[0]?.bbox.x).toBe(0.2);
});

it('uses the presented video PTS, without a second easing delay or score-order matching', () => {
  const a = frame(90_000);
  const b = frame(126_000);
  const head = {
    displayState: 'alert',
    visibleByDefault: true,
    displayBoxX: 0.12,
    displayBoxY: 0.22,
    displayBoxWidth: 0.05,
    displayBoxHeight: 0.06,
  };
  a.objects = [
    { ...object, attributes: head },
    {
      ...object,
      trackId: 'track-2',
      confidence: 0.6,
      bbox: { ...object.bbox, x: 0.55 },
      attributes: { ...head, displayBoxX: 0.57 },
    },
  ];
  b.objects = [
    { ...a.objects[1]!, confidence: 0.95 },
    {
      ...a.objects[0]!,
      confidence: 0.5,
      bbox: { ...object.bbox, x: 0.3 },
      attributes: { ...head, displayBoxX: 0.32 },
    },
  ];
  for (let ms = 0; ms <= 400; ms += 40) {
    const result = alignedOverlay([a, b], {
      streamId,
      sourcePts: 90_000 + ms * 90,
    });
    const positions = new Map(
      result?.frame.objects.map((o) => [o.trackId, o.attributes.displayBoxX]),
    );
    expect(positions.get('track-1')).toBeCloseTo(0.12 + (0.2 * ms) / 400);
    expect(positions.get('track-2')).toBeCloseTo(0.57);
  }
  expect(
    alignedOverlay([a, b], { streamId, sourcePts: 139_500 })?.frame.objects.map(
      (o) => o.trackId,
    ),
  ).toEqual(['track-2']);
});

it('requires another observation before retaining an unmeasured target beyond 100 ms', () => {
  expect(
    alignedOverlay([frame(90_000)], { streamId, sourcePts: 99_000 })?.frame
      .objects,
  ).toHaveLength(1);
  expect(
    alignedOverlay([frame(90_000)], { streamId, sourcePts: 99_090 })?.frame
      .objects,
  ).toEqual([]);
});
