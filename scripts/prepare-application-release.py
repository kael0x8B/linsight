#!/usr/bin/env python3
"""Prepare the bundled ARM64 publisher on Windows, Linux or macOS, offline."""
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, NoEncryption, PrivateFormat, PublicFormat, load_pem_private_key

ROOT = Path(__file__).resolve().parents[1]


def yaml_value(value):
    return "'" + str(value).replace("'", "''") + "'"


def prepare(root=ROOT, *, replace_config=False):
    if sys.version_info < (3, 12):
        raise RuntimeError("发布构建需要 Python 3.12 或以上版本")
    baseline = root / "deploy/application-release/baseline"
    manifest = json.loads((baseline / "manifest.json").read_text(encoding="utf-8"))
    if hashlib.sha256((root / "runtime/pyproject.toml").read_bytes()).hexdigest() != manifest["pyprojectSha256"]:
        raise ValueError("Runtime 依赖已变更，请重新生成发布依赖基线")
    for item in manifest["files"]:
        source, destination = baseline / item["path"], root / item["path"]
        if not destination.resolve().is_relative_to((root / "runtime").resolve()):
            raise ValueError("发布基线路径无效")
        if source.stat().st_size != item["size"] or hashlib.sha256(source.read_bytes()).hexdigest() != item["sha256"]:
            raise ValueError("发布依赖校验失败: " + item["path"])
    for item in manifest["files"]:
        destination = root / item["path"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(baseline / item["path"], destination)
    configuration = root / "var/application-release-local.yaml"
    if configuration.exists() and not replace_config:
        print(f"[ok] 发布依赖已就绪；保留已有发布配置: {configuration}")
        return configuration
    keys = root / "var/application-release/keys"
    keys.mkdir(parents=True, exist_ok=True)
    private = keys / "release.key"
    if not private.exists():
        private.write_bytes(Ed25519PrivateKey.generate().private_bytes(Encoding.PEM, PrivateFormat.PKCS8, NoEncryption()))
        private.chmod(0o600)
    signing_key = load_pem_private_key(private.read_bytes(), password=None)
    if not isinstance(signing_key, Ed25519PrivateKey):
        raise ValueError("发布密钥类型必须为 Ed25519")
    public = signing_key.public_key().public_bytes(Encoding.PEM, PublicFormat.SubjectPublicKeyInfo)
    key_id = "publisher-" + hashlib.sha256(public).hexdigest()[:12]
    (keys / "release-public.pem").write_bytes(public)
    paths = {"runtime": root / "runtime", "python": root / manifest["pythonArchive"],
             "wheels": root / manifest["wheelsDirectory"], "key": private,
             "builder": root / "scripts/build-box-release.py", "output": root / "var/application-releases"}
    p = {name: yaml_value(path.resolve().as_posix()) for name, path in paths.items()}
    configuration.write_text(f"""# Generated by prepare-application-release.py. Local-only, contains publisher paths.
linsight:
  ai-video:
    node-deployment:
      runtime-source-dir: {p['runtime']}
    node-application-release:
      enabled: true
      python-executable: {yaml_value(Path(sys.executable).resolve().as_posix())}
      builder-script: {p['builder']}
      output-directory: {p['output']}
      default-profile: arm64
      profiles:
        arm64:
          label: ARM64 统一应用升级包
          architecture: aarch64
          devices: [rk3566, rk3568, rk3588]
          min-glibc: '{manifest['minGlibc']}'
          python-archive: {p['python']}
          python-sha256: {manifest['pythonSha256']}
          wheels-directory: {p['wheels']}
          signing-key: {p['key']}
          key-id: {key_id}
""", encoding="utf-8")
    configuration.chmod(0o600)
    print(f"[ok] 升级包发布配置已生成: {configuration}；重启 IDEA 后端后生效")
    return configuration


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replace-config", action="store_true", help="重新生成路径配置，保留本机发布私钥")
    prepare(replace_config=parser.parse_args().replace_config)
