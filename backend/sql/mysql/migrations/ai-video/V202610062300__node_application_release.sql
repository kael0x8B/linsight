-- Durable application-package build queue. No existing node rows or configuration are changed.
-- Deploy before enabling the worker. Rollback: disable generation; retain this audit table.
CREATE TABLE IF NOT EXISTS ai_node_application_release (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_id BIGINT NOT NULL DEFAULT 0,
 request_id VARCHAR(64) NOT NULL,
 profile_id VARCHAR(64) NOT NULL,
 profile_label VARCHAR(200) NOT NULL,
 profile_digest CHAR(64) NOT NULL,
 architecture VARCHAR(16) NOT NULL,
 devices VARCHAR(100) NOT NULL,
 key_id VARCHAR(64) NOT NULL,
 version VARCHAR(64) NOT NULL,
 notes TEXT NOT NULL,
 status VARCHAR(20) NOT NULL,
 message VARCHAR(500) NOT NULL,
 executor_owner VARCHAR(64) NULL,
 lease_until DATETIME NULL,
 attempt INT NOT NULL DEFAULT 1,
 bundle_file_id BIGINT NULL,
 bootstrap_file_id BIGINT NULL,
 public_key_file_id BIGINT NULL,
 file_name VARCHAR(200) NULL,
 size BIGINT NULL,
 sha256 CHAR(64) NULL,
 bootstrap_sha256 CHAR(64) NULL,
 source_sha256 CHAR(64) NULL,
 finish_time DATETIME NULL,
 creator VARCHAR(64) DEFAULT '',
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updater VARCHAR(64) DEFAULT '',
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 deleted BIT NOT NULL DEFAULT b'0',
 UNIQUE KEY uk_tenant_request(tenant_id, request_id),
 UNIQUE KEY uk_tenant_profile_version(tenant_id, profile_id, version),
 KEY idx_status_lease(status, lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
